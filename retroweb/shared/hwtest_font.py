def _segment(a, b):
    (x0, y0), (x1, y1) = a, b
    n = max(abs(x1 - x0), abs(y1 - y0))
    if n == 0:
        return [a]
    return [(x0 + (x1 - x0) * i // n if x1 >= x0 else x0 - (x0 - x1) * i // n,
             y0 + (y1 - y0) * i // n if y1 >= y0 else y0 - (y0 - y1) * i // n)
            for i in range(n + 1)]


def glyph(ch):
    rows = [0] * 8
    for stroke in STROKES[ch]:
        pts = stroke if len(stroke) > 1 else stroke * 2
        for a, b in zip(pts, pts[1:]):
            for x, y in _segment(a, b):
                rows[y] |= 0x80 >> (X0 + x)
    return tuple(rows)


def font(chars):
    """Return {char: 8 row bytes} for chars. Bit 7 = left."""
    return {ch: glyph(ch) for ch in chars}
